import { expect, test } from '@playwright/test'

test('public homepage fits desktop tablet and mobile and loads its construction image', async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const widths = testInfo.project.name.startsWith('mobile') ? [390] : [1440, 768]
  for (const width of widths) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Crafted for the builders')
    const heroPhoto = page.locator('.sales-hero-photo')
    await expect(heroPhoto).toBeVisible()
    expect(await heroPhoto.evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true)
    await expect(page.getByRole('tablist', { name: 'Architectural perspectives' })).toBeVisible()
    const workflowImage = page.getByRole('img', { name: /Residential inspector documenting/ })
    await expect(workflowImage).toBeVisible()
    expect(await workflowImage.evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.locator('.sales-construction')).toHaveCSS('opacity', '1')
    if (width === 1440) {
      const heroBox = await page.locator('.sales-hero').boundingBox()
      expect(heroBox).not.toBeNull()
      expect(heroBox!.height).toBeLessThanOrEqual(920)
      const workflowBox = await page.locator('.sales-workflow').boundingBox()
      expect(workflowBox).not.toBeNull()
      expect(workflowBox!.height).toBeLessThanOrEqual(860)
    }
    await page.screenshot({ path: testInfo.outputPath(`buildtrack-first-viewport-${width}.png`) })
    for (const selector of ['.sales-workflow .sales-section-heading', '.sales-workflow-body', '.sales-team-section .sales-section-heading', '.sales-team-layout', '.sales-field-heading', '.sales-field-visual', '.sales-contact .sales-container > div']) {
      const section = page.locator(selector)
      await section.scrollIntoViewIfNeeded()
      await expect(section).toHaveCSS('opacity', '1')
    }
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath(`buildtrack-homepage-${width}.png`), fullPage: true, animations: 'disabled' })
  }
  expect(errors).toEqual([])
})

test('workflow and team exploration respond to user choices', async ({ page }) => {
  await page.goto('/')
  const steps = page.getByRole('group', { name: 'Explore the workflow' })
  await steps.getByRole('button', { name: /Verify/ }).click()
  await expect(page.getByRole('heading', { name: 'Close it with confidence.' })).toBeVisible()
  await expect(page.getByText('Repair accepted', { exact: true })).toBeVisible()
  await expect(steps.getByRole('button', { name: /Verify/ })).toHaveAttribute('aria-pressed', 'true')
  await steps.getByRole('button', { name: /Assign/ }).click()
  await expect(page.getByRole('heading', { name: 'Give every issue an owner.' })).toBeVisible()
  await page.getByRole('button', { name: 'Trade partners', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Vendor Manager', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Org Admin', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Field teams', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Inspector', exact: true })).toBeVisible()
})

test('demo inquiry prepares an email draft without posting a lead or claiming delivery', async ({ page }) => {
  const writes: string[] = []
  page.on('request', (request) => { if (request.method() === 'POST') writes.push(request.url()) })
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/')
  await page.locator('.sales-hero').getByRole('button', { name: 'Request a demo' }).click()
  const dialog = page.getByRole('dialog', { name: 'Your team. Your workflow.' })
  await expect(dialog).toBeVisible()
  const box = await dialog.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThan(200)
  expect(box!.y).toBeGreaterThan(40)
  await dialog.getByRole('textbox', { name: 'Your name' }).fill('Casey Builder')
  await dialog.getByRole('textbox', { name: 'Company', exact: true }).fill('Oak & Pine Builders')
  await dialog.getByRole('textbox', { name: 'Work email' }).fill('casey@example.test')
  await dialog.getByRole('combobox', { name: 'Homes built per year' }).selectOption('100–500')
  await dialog.getByRole('button', { name: 'Prepare demo inquiry' }).click()
  const draft = dialog.getByRole('link', { name: 'Open email draft' })
  await expect(draft).toHaveAttribute('href', /^mailto:support@vkr-ventures.com\?subject=/)
  const href = await draft.getAttribute('href')
  expect(decodeURIComponent(href!)).toContain('Oak & Pine Builders')
  expect(decodeURIComponent(href!)).toContain('casey@example.test')
  expect(writes).toEqual([])
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})

test('reduced-motion visitors can use mobile navigation and reach sign-in', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const toggle = page.getByRole('button', { name: 'Open menu' })
  await toggle.click()
  await expect(page.getByRole('navigation', { name: 'Website navigation' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(toggle).toBeFocused()
  await toggle.click()
  await page.getByRole('navigation', { name: 'Website navigation' }).getByRole('link', { name: 'Sign in' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('heading', { name: 'Sign in to your workspace' })).toBeVisible()
  await page.getByRole('link', { name: 'BuildTrack home', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Crafted for the builders')
})
